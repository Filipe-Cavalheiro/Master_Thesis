def get_initial_real_offset(
    param: Param,
    iD: int | None = None,
    phase: str = "Main Controller",
    flip_pitch: bool = True,
):
    """
    Return the real drone(s)' initial state at the start of a flight phase.

    Parameters
    ----------
    param : Param
        Must provide param.sim.real_trajectory_csv.
    iD : int or None
        ID of the desired drone. If None, extract all drones found in the
        CSV. If the CSV has no 'id' column, assume a single drone.
    phase : str
        Value of the 'flight_state' column marking the interval of interest.
    flip_pitch : bool
        If True, negate pitch before constructing the rotation matrix.

    Returns
    -------
    position : np.ndarray or list[np.ndarray]
        Shape (3, 1) for one selected drone, or a list of (3, 1) arrays
        when extracting multiple drones.
    velocity : np.ndarray or list[np.ndarray]
        Shape (3, 1) for one selected drone, or a list of (3, 1) arrays.
    attitude : np.ndarray or list[np.ndarray]
        Shape (9, 1) for one selected drone, or a list of (9, 1) arrays.
        Each array contains a flattened row-major 3x3 rotation matrix.
    ang_vel : np.ndarray or list[np.ndarray]
        Shape (3, 1) for one selected drone, or a list of (3, 1) arrays.
    time0 : float or list[float]
        Timestamp of the selected initial sample for each drone.
        A scalar is returned when selecting a single drone.

    Notes
    -----
    When iD is None and the CSV contains an 'id' column, the four state
    outputs and time0 are lists ordered by drone ID. Each drone is
    initialized from its own first complete sample in the requested phase.

    If the CSV has no 'id' column, a single drone is assumed, and the
    four state outputs and time0 are returned as individual values.
    """

    csv_path = Path(param.sim.real_trajectory_csv)

    if not csv_path.exists():
        raise FileNotFoundError(
            f"Real trajectory CSV not found: {csv_path}"
        )

    df = pd.read_csv(csv_path)

    required = ["time_s", "flight_state", *EST_COLS]
    missing = [col for col in required if col not in df.columns]

    if missing:
        raise ValueError(
            f"Missing required CSV columns: {missing}"
        )

    # Convert estimator and timestamp columns to numeric values.
    numeric_cols = list(dict.fromkeys(["time_s", *EST_COLS]))

    for col in numeric_cols:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    # Normalize flight-state labels and select the requested phase.
    states = df["flight_state"].fillna("").astype(str).str.strip()
    df_phase = df.loc[states.eq(phase)].copy()

    if df_phase.empty:
        available = sorted(s for s in states.unique() if s)

        raise ValueError(
            f"Flight state '{phase}' not found in CSV. "
            f"Available: {available}"
        )

    # Ignore samples with incomplete estimator data.
    df_phase = df_phase.dropna(subset=numeric_cols)

    if df_phase.empty:
        raise ValueError(
            f"No complete estimator samples found in phase '{phase}'."
        )

    has_id = "id" in df_phase.columns

    if has_id:
        # Exclude rows without a valid drone ID.
        df_phase = df_phase.dropna(subset=["id"])

        if df_phase.empty:
            raise ValueError(
                f"No valid drone IDs found in phase '{phase}'."
            )

        # Select one drone or all drones.
        if iD is not None:
            ids = pd.to_numeric(df_phase["id"], errors="coerce")
            df_phase = df_phase.loc[ids.eq(iD)]

            if df_phase.empty:
                available = sorted(
                    pd.to_numeric(
                        df["id"], errors="coerce"
                    ).dropna().unique().tolist()
                )

                raise ValueError(
                    f"Drone ID {iD} has no complete estimator samples "
                    f"in phase '{phase}'. Available IDs: {available}"
                )

            drone_ids = [iD]
        else:
            drone_ids = sorted(df_phase["id"].unique().tolist())
            if len(drone_ids) < param.sim.nD:
                raise ValueError(
                    f"Not enougth drone in experimental setup"
                    f"Total available drone: {len(drone_ids)}, drones desired: {param.sim.nD}"
                )

    else:
        # Without an ID column, assume there is just one drone.
        drone_ids = [None]

    positions = []
    velocities = []
    attitudes = []
    angular_velocities = []
    timestamps = []

    # Get each drone's own first complete sample in the phase.
    for drone_id in drone_ids:
        if has_id:
            drone_df = df_phase.loc[
                df_phase["id"].eq(drone_id)
            ]
        else:
            drone_df = df_phase

        # Use the earliest timestamp, not necessarily the first CSV row.
        row = drone_df.loc[drone_df["time_s"].idxmin()]

        # Initial position and velocity.
        position = row[
            ["est_x", "est_y", "est_z"]
        ].to_numpy(dtype=np.float64).reshape(3, 1)

        velocity = row[
            ["est_vx", "est_vy", "est_vz"]
        ].to_numpy(dtype=np.float64).reshape(3, 1)

        # Convert Euler angles from degrees to radians.
        roll = np.deg2rad(row["roll_deg"])
        pitch = np.deg2rad(row["pitch_deg"])
        yaw = np.deg2rad(row["yaw_deg"])

        if flip_pitch:
            pitch = -pitch

        # Flatten the rotation matrix in row-major order.
        attitude = np.asarray(
            Euler2R([roll, pitch, yaw]),
            dtype=np.float64,
        ).reshape(9, 1)

        # Convert body angular rates from degrees/s to radians/s.
        ang_vel = np.deg2rad(
            row[
                ["gyro_x_dps", "gyro_y_dps", "gyro_z_dps"]
            ].to_numpy(dtype=np.float64)
        ).reshape(3, 1)

        positions.append(position)
        velocities.append(velocity)
        attitudes.append(attitude)
        angular_velocities.append(ang_vel)
        timestamps.append(float(row["time_s"]))

    # Return individual arrays for a single drone
    # Return lists when multiple drones are requested.
    if len(drone_ids) == 1:
        return (
            positions[0],
            velocities[0],
            attitudes[0],
            angular_velocities[0],
            timestamps[0],
        )

    return (
        positions,
        velocities,
        attitudes,
        angular_velocities,
        timestamps,
    )

def _exp_so3(phi):
    """Rodrigues formula: rotation vector -> rotation matrix."""
    phi = np.asarray(phi).ravel()
    theta = np.linalg.norm(phi)
    K = skew(phi)
    if theta < 1e-9:
        return np.eye(3) + K + 0.5 * K @ K
    return (np.eye(3)
            + np.sin(theta) / theta * K
            + (1 - np.cos(theta)) / theta**2 * K @ K)

def rk4_step_rigid_body(deriv, p, v, R, om, dt):
    """
    One RK4 step for a rigid body.

    deriv(p, v, R, om) -> (dot_p, dot_v, dot_om)
    R is a 3x3 rotation matrix; om is the body-frame angular velocity (R_dot = R @ hat(om)).
    Position, velocity and angular velocity use standard RK4. The attitude is
    propagated on SO(3) using intermediate rotations and an RK4-weighted
    angular velocity, so R stays orthonormal.
    """
    # Stage 1
    k1p, k1v, k1o = deriv(p, v, R, om)
    om1 = om

    # Stage 2
    om2 = om + 0.5 * dt * k1o
    R2 = R @ _exp_so3(0.5 * dt * om1)
    k2p, k2v, k2o = deriv(p + 0.5 * dt * k1p, v + 0.5 * dt * k1v, R2, om2)

    # Stage 3
    om3 = om + 0.5 * dt * k2o
    R3 = R @ _exp_so3(0.5 * dt * om2)
    k3p, k3v, k3o = deriv(p + 0.5 * dt * k2p, v + 0.5 * dt * k2v, R3, om3)

    # Stage 4
    om4 = om + dt * k3o
    R4 = R @ _exp_so3(dt * om3)
    k4p, k4v, k4o = deriv(p + dt * k3p, v + dt * k3v, R4, om4)

    p_new  = p  + dt / 6 * (k1p + 2*k2p + 2*k3p + k4p)
    v_new  = v  + dt / 6 * (k1v + 2*k2v + 2*k3v + k4v)
    om_new = om + dt / 6 * (k1o + 2*k2o + 2*k3o + k4o)

    om_eff = (om1 + 2*om2 + 2*om3 + om4) / 6
    R_new = R @ _exp_so3(dt * om_eff)

    return p_new, v_new, R_new, om_new