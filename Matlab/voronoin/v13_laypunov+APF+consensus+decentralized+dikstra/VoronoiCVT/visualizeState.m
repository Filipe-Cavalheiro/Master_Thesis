function visualizeState(state, ttl, gfx, Param)

    V = state.vertices;
    F = state.faces;
    N = size(V,1);

    set(gfx.surf, ...
        'Faces', F, ...
        'Vertices', V, ...
        'FaceVertexCData', zeros(N,1));

    pts = V(state.sites,:);

    set(gfx.voronoi_edges, ...
        'XData', nan, ...
        'YData', nan, ...
        'ZData', nan);

    set(gfx.sites, ...
        'XData', pts(:,1), ...
        'YData', pts(:,2), ...
        'ZData', pts(:,3));

    title(sprintf('%s | Object: %s', ttl, Param.objList{state.obj_index}));
end