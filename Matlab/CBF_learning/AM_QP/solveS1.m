function zeta = solveS1(...
    Q,...
    q,...
    A,...
    b,...
    C,...
    e,...
    rho,...
    lambda)

Abar = Q + rho*(A'*A);

bbar = -q ...
       + rho*A'*b ...
       - lambda;

KKT = [
    Abar C';
    C zeros(size(C,1))
];

rhs = [
    bbar;
    e
];

sol = KKT\rhs;

zeta = sol(1:size(Q,1));
end